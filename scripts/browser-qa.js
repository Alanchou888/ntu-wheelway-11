async (page) => {
  const base = 'http://localhost:5173/'
  const results = []
  const assert = (value, name) => { if (!value) throw new Error(name); results.push({ name, pass: true }) }
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.goto(base)
  await page.getByRole('heading', { name: '下一段，往哪裡？' }).waitFor()
  assert(await page.getByRole('radio', { name: '較平緩 優先較小坡度', exact: true }).isChecked(), 'Default preference: gentle')
  await page.getByText('電動輪椅', { exact: true }).click()
  await page.getByRole('button', { name: '交換起點與終點' }).click()
  assert(await page.getByRole('combobox', { name: '起點', exact: true }).inputValue() === 'boya', 'Swap origin and destination')
  await page.getByText('距離較短', { exact: true }).first().click()
  await page.getByRole('button', { name: '查詢候選路線' }).click()
  await page.getByRole('heading', { name: '找到 2 條示範動線' }).waitFor()
  assert((await page.locator('button.route-card').first().getAttribute('aria-label')).includes('距離較短'), 'Distance preference orders shorter route first')
  await page.screenshot({ path: 'output/playwright/desktop-compare.png' })
  await page.getByRole('button', { name: '查看較平緩的動線', exact: true }).click()
  await page.getByRole('button', { name: /路段 2：/ }).click()
  assert(await page.getByRole('button', { name: /路段 2：/ }).getAttribute('aria-pressed') === 'true', 'Segment list changes selected segment')
  await page.getByText('資料依據與查核資訊', { exact: true }).click()
  assert(await page.locator('.evidence-details').getByText(/尚未查核/).count() > 0, 'Demo never claims a field verification date')
  await page.screenshot({ path: 'output/playwright/desktop-detail.png' })
  await page.getByRole('button', { name: '選擇這條路線', exact: true }).click()
  await page.getByRole('heading', { name: '路線已選好' }).waitFor()
  await page.getByText('博雅教學館示範入口', { exact: true }).click()
  assert(await page.getByText('示範入口位置，尚待團隊實地確認', { exact: true }).count() > 0, 'Entrance evidence visible independently of building center')
  const share = page.url()
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('button', { name: '複製路線連結' }).click()
  await page.getByText('路線連結已複製', { exact: true }).waitFor()
  assert((await page.evaluate(() => navigator.clipboard.readText())).includes('screen=confirm'), 'Share link copied')
  await page.screenshot({ path: 'output/playwright/desktop-confirm.png' })
  await page.goto(share)
  await page.getByRole('heading', { name: '路線已選好' }).waitFor()
  assert(page.url().includes('from=boya') && page.url().includes('chair=electric'), 'Shared link restores direction, wheelchair and route')
  await page.getByRole('button', { name: '已查核路線', exact: true }).click()
  await page.getByRole('heading', { name: '目前無已查核路線', exact: true }).waitFor()
  assert(await page.locator('button.route-card').count() === 0, 'Survey mode excludes demo routes')
  await page.screenshot({ path: 'output/playwright/desktop-no-survey.png' })
  await page.getByRole('button', { name: '試用兩條示範路線' }).click()
  await page.getByRole('heading', { name: '找到 2 條示範動線' }).waitFor()
  await page.getByRole('button', { name: '資料來源', exact: true }).click()
  assert(await page.getByRole('dialog').isVisible(), 'Source modal opens')
  await page.keyboard.press('Tab')
  assert(await page.evaluate(() => !!document.activeElement?.closest('dialog')), 'Keyboard focus stays inside source dialog')
  await page.keyboard.press('Escape')
  assert(await page.getByRole('dialog').count() === 0, 'Escape closes source modal')
  for (const width of [390, 360]) {
    await page.setViewportSize({ width, height: 844 })
    await page.goto(base)
    await page.getByRole('heading', { name: '下一段，往哪裡？' }).waitFor()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `No horizontal overflow at ${width}px`)
    const size = await page.getByRole('button', { name: '查詢候選路線' }).boundingBox()
    assert(size.width >= 44 && size.height >= 44, `Primary mobile target at ${width}px is at least 44px`)
    await page.screenshot({ path: `output/playwright/mobile-${width}-setup.png`, fullPage: true })
    await page.getByRole('button', { name: '查詢候選路線' }).click()
    await page.getByRole('heading', { name: '找到 2 條示範動線' }).waitFor()
    assert((await page.locator('button.route-card').first().getAttribute('aria-label')).includes('較平緩'), `Gentle order at ${width}px`)
    await page.screenshot({ path: `output/playwright/mobile-${width}-compare.png`, fullPage: true })
    await page.getByRole('button', { name: '查看較平緩的動線' }).click()
    await page.getByRole('button', { name: '選擇這條路線' }).click()
    await page.getByRole('heading', { name: '路線已選好' }).waitFor()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Confirm has no overflow at ${width}px`)
  }
  await page.addScriptTag({ path: 'node_modules/axe-core/axe.min.js' })
  const axe = await page.evaluate(async () => {
    const r = await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a','wcag2aa','wcag21a','wcag21aa'] } })
    return r.violations.map(v => ({ id: v.id, impact: v.impact, description: v.description, nodes: v.nodes.map(n => ({ html: n.html, summary: n.failureSummary, target: n.target })) }))
  })
  assert(axe.length === 0, 'No automated WCAG A/AA violations on mobile confirmation')
  return { results, accessibilityViolations: axe }
}
